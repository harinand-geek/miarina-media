/// The brand mark of [url]'s site, if the app ships one.
BrandMark? brandMarkFor(String url) {
  var host = Uri.tryParse(url)?.host.toLowerCase() ?? '';
  while (host.isNotEmpty) {
    final mark = _byHost[host];
    if (mark != null) return mark;
    final dot = host.indexOf('.');
    if (dot < 0) break;
    host = host.substring(dot + 1);
  }
  return null;
}
