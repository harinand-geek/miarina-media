void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln(
      'usage: dart run tool/gen_icons.dart <@phosphor-icons/web package dir>',
    );
    exit(64);
  }
  final pkg = args.single;
  final version = RegExp(r'"version":\s*"([^"]+)"')
      .firstMatch(File('$pkg/package.json').readAsStringSync())!
      .group(1);
  final regular = _codepoints(File('$pkg/src/regular/style.css'), 'ph');
  final fill = _codepoints(File('$pkg/src/fill/style.css'), 'ph-fill');

  final table = File('../../docs/icon-system.md').readAsStringSync();
  final names = <String>{
    for (final m in RegExp(
      r'^\| `[a-z0-9_]+` \| `([a-z0-9-]+)` \|',
      multiLine: true,
    ).allMatches(table))
      m.group(1)!,
    ..._extras,
  }.toList()..sort();

  final missing = names.where((n) => !regular.containsKey(n)).toList();
  if (missing.isNotEmpty) {
    stderr.writeln('not in Phosphor $version: ${missing.join(', ')}');
    exit(1);
  }

  final out = StringBuffer()
    ..writeln(
      '// Generated by tool/gen_icons.dart from @phosphor-icons/web $version',
    )
    ..writeln('// (MIT, Phosphor Icons). Do not edit; see docs/icon-system.md.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln();
  _class(out, 'PhosphorRegular', 'PhosphorRegular', names, regular);
  out.writeln();
  _class(
    out,
    'PhosphorFill',
    'PhosphorFill',
    names.where(fill.containsKey),
    fill,
  );

  File('lib/design/mm_icons.g.dart').writeAsStringSync(out.toString());
  Directory('assets/icons').createSync(recursive: true);
  File('$pkg/src/regular/Phosphor.ttf').copySync('assets/icons/Phosphor.ttf');
  File('$pkg/src/fill/Phosphor-Fill.ttf')
      .copySync('assets/icons/Phosphor-Fill.ttf');
  File('$pkg/LICENSE').copySync('assets/icons/LICENSE-Phosphor.txt');
  stdout.writeln('${names.length} icons from Phosphor $version');
}

Map<String, int> _codepoints(File css, String prefix) {
  final pattern = RegExp(
    '\\.${RegExp.escape(prefix)}\\.ph-([a-z0-9-]+):before\\s*\\{\\s*content:\\s*"\\\\([0-9a-f]+)"',
  );
  return {
    for (final m in pattern.allMatches(css.readAsStringSync()))
      m.group(1)!: int.parse(m.group(2)!, radix: 16),
  };
}

void _class(
  StringBuffer out,
  String name,
  String family,
  Iterable<String> icons,
  Map<String, int> codes,
) {
  out.writeln('abstract final class $name {');
  for (final icon in icons) {
    final hex = codes[icon]!.toRadixString(16);
    out.writeln(
      "  static const IconData ${_camel(icon)} = IconData(0x$hex, fontFamily: '$family');",
    );
  }
  out.writeln('}');
}

String _camel(String kebab) {
  final parts = kebab.split('-');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}
