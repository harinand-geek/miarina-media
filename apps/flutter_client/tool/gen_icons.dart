// Generates lib/design/mm_icons.g.dart from the official Phosphor web font
// package (@phosphor-icons/web) and the icon list in docs/icon-system.md.
//
//   dart run tool/gen_icons.dart <path to @phosphor-icons/web package>
//
// The package's Phosphor.ttf and Phosphor-Fill.ttf are copied to
// assets/icons/; Flutter's icon tree shaking keeps only the glyphs used.
